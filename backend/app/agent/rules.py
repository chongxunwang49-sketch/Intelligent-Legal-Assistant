def detect_contract_type(text: str) -> str:
    for ctype, keys in CONTRACT_TYPE_KEYWORDS.items():
        hit = sum(1 for k in keys if k in text)
        if hit >= 2:
            return ctype
    return "买卖"


def required_clauses(contract_type: str) -> list[str]:
    return CONTRACT_TEMPLATES.get(contract_type, DEFAULT_TEMPLATE)


def match_risk_rules(text: str) -> list[dict]:
    """对给定条款文本跑全部确定性规则，返回命中列表。"""
    hits = []
    for rule in RISK_RULES:
        if rule["pattern"].search(text):
            hits.append(
                {
                    "risk_type": rule["risk_type"],
                    "level": rule["level"],
                    "risk_description": rule["desc"],
                    "suggestion": rule["suggestion"],
                    "legal_basis": rule["basis"],
                }
            )
    return hits
